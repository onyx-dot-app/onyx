"""Write rule files from the rule registry draft.

    python3 tools/semantic-lint/mining/write_rules.py DRAFT_JSON --corpus CORPUS_DIR \
        [--out RULES_DIR] [--ids ID ...]

Each criteria example cites the review thread its code came from
(`criteria_example_sources`), so eval never scores a rule on code Jev sees as
its example. The corpus (`pull_comments.jsonl`) is read only, for the
reviewer's words when the draft has no excerpt.
"""

import argparse
import json
import re
import sys
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from semantic_lint.registry import (  # noqa: E402
    RULES_DIR,
    SETTINGS_FILE,
    Family,
    RegistryError,
    RuleId,
    Severity,
    load_registry,
)

HEADER = "# Generated by mining/write_rules.py from the rule registry draft. Edit by hand after."
QUOTE_CHARS = 200
INLINE_ARRAY_CHARS = 80
SEVERITIES: Mapping[str, Severity] = {
    "nit": Severity.NIT,
    "should_fix": Severity.FIX,
    "must_fix": Severity.FIX,
}
NEVER_FLAG_TEXT_KEYS = ("dismissed_pattern", "bot_pattern", "pattern", "text")

_RULE_ID = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
# Control characters a TOML multi-line literal string cannot hold.
_CONTROL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
_NEVER_FLAG = re.compile(r"^never_flag = \[(?:\]|\n(?:.*\n)*?\])$", re.MULTILINE)

type JsonObject = dict[str, object]


class DraftError(Exception):
    """The draft, corpus or anti-rule file does not have the expected shape."""


@dataclass(frozen=True)
class Example:
    thread: int
    hunk: str
    said: str


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    out: Path = args.out
    try:
        draft = _object(json.loads(Path(args.draft).read_text()), "draft")
        rules = _objects(draft, "rules", "draft")
        if args.ids:
            rules = _select(rules, args.ids)
        corpus = _corpus(Path(args.corpus) / "pull_comments.jsonl", _threads(rules))
        written: list[RuleId] = []
        for raw in rules:
            rule_id = _rule_id(raw)
            (out / f"{rule_id}.toml").write_text(_render_rule(raw, corpus))
            written.append(RuleId(rule_id))
        never_flag = [
            _never_flag_text(item, f"draft never_flag[{index}]")
            for index, item in enumerate(_list(draft, "never_flag", "draft"))
        ]
        if never_flag and not args.ids:
            _write_never_flag(out / SETTINGS_FILE, never_flag)
        registry = load_registry(out).only(written)
    except (DraftError, RegistryError, OSError, json.JSONDecodeError) as error:
        print(f"write_rules: {error}", file=sys.stderr)
        return 1
    for rule in registry.rules:
        attributed = sum(1 for flag in rule.flag_examples if flag.quote)
        print(
            f"{rule.id:<48} {rule.family.value:<9} {rule.severity.value:<3} "
            f"sources={len(rule.sources):<3} "
            f"flags={len(rule.flag_examples)} ({attributed} attributed) "
            f"cleans={len(rule.clean_examples)}"
        )
    return 0


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Write rule files from the draft.")
    parser.add_argument("draft", help="registry_draft.json")
    parser.add_argument("--corpus", required=True, help="dir with pull_comments.jsonl")
    parser.add_argument("--out", type=Path, default=RULES_DIR, help="rules dir")
    parser.add_argument("--ids", nargs="+", help="write only these rule ids")
    return parser.parse_args(argv)


def _select(rules: list[JsonObject], ids: Sequence[str]) -> list[JsonObject]:
    by_id = {_rule_id(raw): raw for raw in rules}
    unknown = sorted(set(ids) - set(by_id))
    if unknown:
        raise DraftError(f"rule ids not in the draft: {', '.join(unknown)}")
    return [by_id[rule_id] for rule_id in dict.fromkeys(ids)]


def _threads(rules: Iterable[JsonObject]) -> set[int]:
    threads: set[int] = set()
    for raw in rules:
        where = _rule_id(raw)
        threads.update(_ints(raw, "source_threads", where))
        for key in ("positive_examples", "negative_examples"):
            threads.update(
                _int(item, "thread_id", where) for item in _objects(raw, key, where)
            )
    return threads


def _corpus(file: Path, wanted: set[int]) -> dict[int, str]:
    bodies: dict[int, str] = {}
    with file.open() as rows:
        for line in rows:
            row = _object(json.loads(line), str(file))
            comment_id = row.get("id")
            if isinstance(comment_id, int) and comment_id in wanted:
                bodies.setdefault(comment_id, _text(row, "body", str(file), ""))
    return bodies


def _render_rule(raw: JsonObject, corpus: Mapping[int, str]) -> str:
    where = _rule_id(raw)
    severity = _text(raw, "severity", where)
    if severity not in SEVERITIES:
        raise DraftError(f"{where}: unknown severity {severity!r}")
    family = _text(raw, "family", where, Family.OTHER.value)
    if family not in {member.value for member in Family}:
        raise DraftError(f"{where}: unknown family {family!r}")
    question = _object(raw.get("jev_question"), f"{where} jev_question")
    criteria = _object(question.get("criteria"), f"{where} criteria")
    true = _object(criteria.get("true"), f"{where} criteria.true")
    false = _object(criteria.get("false"), f"{where} criteria.false")
    example_sources = _object(
        raw.get("criteria_example_sources", {}), f"{where} criteria_example_sources"
    )
    flags = _attributed(true, example_sources, "true", where)
    cleans = _attributed(false, example_sources, "false", where)

    sources = set(_ints(raw, "source_threads", where))
    positives = _examples(raw, "positive_examples", "comment_excerpt", where)
    negatives = {e.thread for e in _examples(raw, "negative_examples", None, where)}
    shown_cleans = {thread for _, thread in cleans if thread is not None}
    near_misses = sorted((negatives | shown_cleans) - sources)
    needs_repo_search = _bool(raw, "needs_repo_search", where)
    hint = (_optional_text(raw, "repo_search_hint", where) or "").strip()
    guidance = "\n\n".join(
        [
            _text(raw, "statement", where).strip(),
            _text(raw, "llm_guidance", where).strip(),
        ]
    )

    top = [
        HEADER,
        f"title = {_string(_text(raw, 'title', where).strip())}",
        f"family = {_string(family)}",
        f"severity = {_string(SEVERITIES[severity].value)}",
        f"sources = {_array([str(thread) for thread in sorted(sources)])}",
    ]
    if near_misses:
        top.append(f"near_misses = {_array([str(t) for t in near_misses])}")
    top.append(f"needs_repo_search = {'true' if needs_repo_search else 'false'}")
    if needs_repo_search and hint:
        top.append(f"repo_search_hint = {_string(hint)}")
    top.append(f"guidance = {_string(guidance)}")

    scope = ["[scope]", f"paths = {_strings(_texts(raw, 'scope_globs', where))}"]
    exclude = _texts(raw, "scope_exclude", where)
    if exclude:
        scope.append(f"exclude = {_strings(exclude)}")

    ask = [
        "[question]",
        f"instructions = {_string(_text(question, 'instructions', where).strip())}",
        f"true_what = {_string(_text(true, 'what', where).strip())}",
    ]
    true_not_for = _texts(true, "not_for", where)
    if true_not_for:
        ask.append(f"true_not_for = {_strings(true_not_for)}")
    ask.append(f"false_what = {_string(_text(false, 'what', where).strip())}")
    false_not_for = _texts(false, "not_for", where)
    if false_not_for:
        ask.append(f"false_not_for = {_strings(false_not_for)}")

    quotes = {thread: _quote(thread, positives, corpus) for thread in sources}
    flag_tables = [
        _table("flag", code, thread, quotes[thread])
        if thread in sources and quotes[thread]
        else _table("flag", code, None, None)
        for code, thread in flags
    ]
    if not flag_tables:
        flag_tables = [
            _table("flag", example.hunk, example.thread, quotes[example.thread])
            for example in positives
            if example.thread in sources
            and example.hunk.strip()
            and quotes[example.thread]
        ]
    clean_tables = [_table("clean", code, thread, None) for code, thread in cleans]
    sections = ["\n".join(top), "\n".join(scope), "\n".join(ask)]
    return "\n\n".join(sections + flag_tables + clean_tables) + "\n"


def _attributed(
    criterion: JsonObject, example_sources: JsonObject, side: str, where: str
) -> list[tuple[str, int | None]]:
    """Each criteria example with the thread the draft says its code came from."""
    threads = [
        thread if isinstance(thread := item.get("thread_id"), int) else None
        for item in _objects(example_sources, side, where)
    ]
    examples = _texts(criterion, "examples", where)
    return [
        (code, threads[index] if index < len(threads) else None)
        for index, code in enumerate(examples)
    ]


def _quote(thread: int, positives: Sequence[Example], corpus: Mapping[int, str]) -> str:
    excerpt = next((ex.said for ex in positives if ex.thread == thread and ex.said), "")
    if not excerpt:
        excerpt = next(iter(corpus.get(thread, "").strip().splitlines()), "")
    return excerpt.strip()[:QUOTE_CHARS].strip()


def _table(header: str, code: str, comment: int | None, said: str | None) -> str:
    lines = [f"[[{header}]]"]
    if comment is not None:
        lines.append(f"comment = {comment}")
    if said is not None:
        lines.append(f"said = {_string(said)}")
    lines.append(f"code = {_string(code, block=True)}")
    return "\n".join(lines)


def _string(value: str, block: bool = False) -> str:
    if (block or "\n" in value) and "'''" not in value and not _CONTROL.search(value):
        return f"'''\n{value}\n'''"
    return _basic(value)


def _basic(value: str) -> str:
    # json.dumps leaves DEL raw, which a TOML basic string must escape.
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def _strings(values: Sequence[str]) -> str:
    return _array([_basic(value.strip()) for value in values])


def _array(items: Sequence[str]) -> str:
    inline = f"[{', '.join(items)}]"
    if len(inline) <= INLINE_ARRAY_CHARS:
        return inline
    return "[\n" + "".join(f"  {item},\n" for item in items) + "]"


def _write_never_flag(settings_file: Path, patterns: Sequence[str]) -> None:
    text = settings_file.read_text()
    rendered = (
        "never_flag = "
        + "[\n"
        + "".join(f"  {_basic(pattern)},\n" for pattern in patterns)
        + "]"
    )
    new, count = _NEVER_FLAG.subn(lambda _: rendered, text, count=1)
    if count != 1:
        raise DraftError(f"{settings_file}: no `never_flag = [...]` array to replace")
    settings_file.write_text(new)


def _never_flag_text(item: object, where: str) -> str:
    if isinstance(item, str):
        text = item
    else:
        raw = _object(item, where)
        texts = [value for value in raw.values() if isinstance(value, str)]
        text = next(
            (
                value
                for key in NEVER_FLAG_TEXT_KEYS
                if isinstance(value := raw.get(key), str)
            ),
            " ".join(texts),
        )
    text = " ".join(text.split())
    if not text:
        raise DraftError(f"{where}: empty never_flag entry")
    return text


def _examples(
    raw: JsonObject, key: str, said_key: str | None, where: str
) -> list[Example]:
    return [
        Example(
            thread=_int(item, "thread_id", where),
            hunk=_text(item, "hunk_excerpt", where, ""),
            said=_text(item, said_key, where, "") if said_key else "",
        )
        for item in _objects(raw, key, where)
    ]


def _rule_id(raw: JsonObject) -> str:
    rule_id = _text(raw, "id", "draft rule")
    if not _RULE_ID.match(rule_id):
        raise DraftError(f"rule id {rule_id!r} is not kebab-case")
    return rule_id


def _object(value: object, where: str) -> JsonObject:
    if not isinstance(value, dict):
        raise DraftError(f"{where}: expected an object")
    return {str(key): item for key, item in value.items()}


def _list(raw: JsonObject, key: str, where: str) -> list[object]:
    value = raw.get(key, [])
    if value is None:
        return []
    if not isinstance(value, list):
        raise DraftError(f"{where}: `{key}` must be a list")
    return list(value)


def _objects(raw: JsonObject, key: str, where: str) -> list[JsonObject]:
    return [_object(item, f"{where} {key}") for item in _list(raw, key, where)]


def _texts(raw: JsonObject, key: str, where: str) -> list[str]:
    value = raw.get(key)
    items = [value] if isinstance(value, str) else _list(raw, key, where)
    if not all(isinstance(item, str) for item in items):
        raise DraftError(f"{where}: `{key}` must be a list of strings")
    return [item for item in items if isinstance(item, str) and item.strip()]


def _ints(raw: JsonObject, key: str, where: str) -> list[int]:
    items = _list(raw, key, where)
    ints = [i for i in items if isinstance(i, int) and not isinstance(i, bool)]
    if len(ints) != len(items):
        raise DraftError(f"{where}: `{key}` must be a list of comment ids")
    return ints


def _int(raw: JsonObject, key: str, where: str) -> int:
    value = raw.get(key)
    if not isinstance(value, int) or isinstance(value, bool):
        raise DraftError(f"{where}: `{key}` must be a comment id")
    return value


def _text(raw: JsonObject, key: str, where: str, default: str | None = None) -> str:
    value = raw.get(key, default)
    if value is None and default is not None:
        return default
    if not isinstance(value, str):
        raise DraftError(f"{where}: `{key}` must be a string")
    return value


def _optional_text(raw: JsonObject, key: str, where: str) -> str | None:
    return _text(raw, key, where) if raw.get(key) is not None else None


def _bool(raw: JsonObject, key: str, where: str) -> bool:
    value = raw.get(key, False)
    if not isinstance(value, bool):
        raise DraftError(f"{where}: `{key}` must be true or false")
    return value


if __name__ == "__main__":
    sys.exit(main())
