#!/usr/bin/env python3
"""Generate CATALOG.md: every Opal and refresh-components component, one line each.

Opal entries come from the README.md beside each component or layout. refresh-
components entries come from the JSDoc block above each file's default export.
Refresh components that Opal replaces are taken from the oxlint rule
`opal/no-replaced-refresh-import`, so the catalog and the lint agree.

Usage: generate_catalog.py [--check]
With --check, exit 1 when CATALOG.md is out of date instead of writing it.
"""

import re
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[3]
_WEB = _REPO / "web"
_OPAL = _WEB / "lib" / "opal" / "src"
_REFRESH = _WEB / "src" / "refresh-components"
_REPLACEMENTS_RULE = (
    _WEB / "tools" / "oxlint" / "opal" / "rules" / "no-replaced-refresh-import.ts"
)
_CATALOG = Path(__file__).resolve().parent / "CATALOG.md"


def _first_sentence(text: str) -> str:
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", " ".join(text.split()))
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return match.group(1) if match else text


def _readme_entry(readme: Path) -> tuple[str, str, str]:
    lines = readme.read_text().splitlines()
    name = lines[0].lstrip("# ").strip() if lines else readme.parent.name
    import_line = next((line for line in lines if line.startswith("**Import:**")), "")
    import_match = re.search(r"from \"([^\"]+)\"", import_line)
    source = import_match.group(1) if import_match else ""
    paragraph: list[str] = []
    for line in lines[1:]:
        if line.startswith(("**Import:**", "#", "|", "```")) or (
            not line.strip() and not paragraph
        ):
            if paragraph:
                break
            continue
        if not line.strip():
            break
        paragraph.append(line)
    return name, source, _first_sentence(" ".join(paragraph))


def _exported_names(kind: str) -> set[str]:
    index = (_OPAL / kind / "index.ts").read_text()
    names: set[str] = set()
    for block in re.findall(r"export\s*\{([^}]*)\}", index):
        for item in block.split(","):
            item = item.strip()
            if item and not item.startswith("type "):
                names.add(item.split(" as ")[-1].strip())
    names.update(re.findall(r"export \* as (\w+)", index))
    return names


def _opal_section(kind: str) -> list[str]:
    exported = _exported_names(kind)
    rows = []
    for readme in sorted((_OPAL / kind).rglob("README.md")):
        if readme.parent == _OPAL / kind:
            continue
        name, source, description = _readme_entry(readme)
        if not source:
            if name.split(".")[0] not in exported:
                continue
            source = f"@opal/{kind}"
        path = readme.relative_to(_WEB).as_posix()
        rows.append(f"| `{name}` | `{source}` | {description} | `{path}` |")
    return rows


def _jsdoc_description(source: str) -> str:
    export = re.search(r"^export default (?:async )?function", source, re.MULTILINE)
    before = source[: export.start()] if export else source
    blocks = re.findall(r"/\*\*(.*?)\*/", before, re.DOTALL)
    if not blocks:
        return ""
    text = re.sub(r"^\s*\* ?", "", blocks[-1], flags=re.MULTILINE)
    text = text.split("@", 1)[0]
    paragraph = text.strip().split("\n\n", 1)[0]
    return _first_sentence(re.sub(r"^\S+ Component\s*", "", paragraph.strip()))


def _replacements() -> dict[str, str]:
    rule = _REPLACEMENTS_RULE.read_text()
    return dict(
        re.findall(r"\[\s*\"(@/refresh-components/[^\"]+)\",\s*\"([^\"]+)\"", rule)
    )


def _refresh_section() -> list[str]:
    replacements = _replacements()
    rows = []
    for path in sorted(_REFRESH.rglob("*.tsx")):
        if path.name.endswith((".stories.tsx", ".test.tsx")):
            continue
        module = (
            "@/refresh-components/"
            + path.relative_to(_REFRESH).with_suffix("").as_posix()
        )
        replacement = replacements.get(module)
        description = (
            f"**Replaced: use {replacement}.**"
            if replacement
            else _jsdoc_description(path.read_text())
            or "No doc comment. Read the file."
        )
        rows.append(f"| `{path.stem}` | `{module}` | {description} |")
    return rows


def render() -> str:
    opal_header = ["| Name | Import | What it is | Docs |", "| --- | --- | --- | --- |"]
    return "\n".join(
        [
            "# Frontend component catalog",
            "",
            "Generated by `generate_catalog.py`. Do not edit by hand.",
            "",
            "## Opal components (`@opal/components`)",
            "",
            *opal_header,
            *_opal_section("components"),
            "",
            "## Opal layouts (`@opal/layouts`)",
            "",
            *opal_header,
            *_opal_section("layouts"),
            "",
            "## refresh-components (use only when Opal has no match)",
            "",
            "| Name | Import | What it is |",
            "| --- | --- | --- |",
            *_refresh_section(),
            "",
        ]
    )


def main() -> int:
    catalog = render()
    if "--check" in sys.argv[1:]:
        if not _CATALOG.exists() or _CATALOG.read_text() != catalog:
            print(
                "CATALOG.md is out of date. Run "
                "python3 .agents/skills/frontend-components/generate_catalog.py",
                file=sys.stderr,
            )
            return 1
        return 0
    _CATALOG.write_text(catalog)
    return 0


if __name__ == "__main__":
    sys.exit(main())
